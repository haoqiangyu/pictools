    final code =
        locale.languageCode == 'zh' &&
            (locale.scriptCode == 'Hant' ||
                ['TW', 'HK', 'MO'].contains(locale.countryCode))
        ? 'zh_Hant'
        : locale.languageCode;
    final index = ['zh', 'en', 'zh_Hant', 'es', 'fr', 'de'].indexOf(code);
    return _studio[key]?[index < 0 ? 1 : index] ?? l10n.t(key);
  }
}

